HOTSPOTS = {"arrow": [0, 0], "look": [5, 6], "talk": [6, 5], "hand": [5, 0], "exit": [13, 8], "wait": [6, 7], "next": [5, 7]}


def main():
    addon = sys.argv[1] if len(sys.argv) > 1 else "addons/adv80s"
    out = os.path.join(addon, "assets", "ui")
    os.makedirs(out, exist_ok=True)
    for name, art in CURSORS.items():
        rows = art.strip("\n").split("\n")
        im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
        for y, row in enumerate(rows[:16]):
            for x, c in enumerate(row[:16]):
                if c == "#":
                    im.putpixel((x, y), (0, 0, 0, 255))
                elif c == "o":
                    im.putpixel((x, y), (255, 255, 255, 255))
        im.save(os.path.join(out, "cursor_%s.png" % name))
        print("wrote cursor_%s.png" % name)


if __name__ == "__main__":
    main()
